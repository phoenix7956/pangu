/**
 * Adapter - 适配器
 * Pangu 2.0: 在 Planner 和 Dispatcher 之间,标准化输入
 * 
 * 职责:
 * - 接收模糊的任务输入(task + 可能的 hints)
 * - 推断 action、path、content、target
 * - 输出标准化的指令给 Dispatcher/Executor
 * 
 * 解决:Executor 5 次 fail 因为 NO_PATH(任务没带具体参数)
 */

const { PanguAgent, registerAgent } = require('./base_agent.js');

class Adapter {
  constructor() {
    this.name = 'Adapter';
    this.role = 'adapter';
  }
  
  /**
   * 适配 task → 标准指令
   * @param {string} task - 任务描述
   * @param {object} ctx - 上下文({ params, hints })
   * @returns {object} 标准化指令 { action, target, params, parsed }
   */
  adapt(task, ctx = {}) {
    const result = {
      original_task: task,
      ctx,
      action: null,
      target: null,
      params: {},
      parsed: {},
      confidence: 0,
    };
    
    const t = task || '';
    const tLower = t.toLowerCase();
    const params = ctx.params || {};
    const hints = ctx.hints || {};
    
    // 1. 推断 action
    result.action = this._inferAction(tLower, hints);
    
    // 2. 推断 target (文件路径/目标)
    if (result.action === 'write_file') {
      result.target = this._inferFilePath(t, params, hints);
    }
    
    // 3. 推断 content (要写什么)
    if (result.action === 'write_file') {
      result.params.content = params.content || hints.content || this._inferContent(t);
    }
    
    // 4. 推断 cmd (要跑什么命令)
    if (result.action === 'exec_command') {
      result.params.cmd = params.cmd || hints.cmd || this._inferCmd(t);
    }
    
    // 5. 推断 message (微信消息)
    if (result.action === 'send_wechat') {
      result.params.message = params.message || hints.message || t;
    }
    
    // 6. confidence 计算(参数完整度)
    let hasAll = 0;
    if (result.action) hasAll++;
    if (result.target || !['write_file', 'exec_command'].includes(result.action)) hasAll++;
    if (result.params.content || result.params.cmd || result.params.message) hasAll++;
    result.confidence = hasAll / 3;
    
    return result;
  }
  
  _inferAction(task, hints) {
    if (hints.action) return hints.action;
    
    // write_file: 写 / 创建 / 代码 / 保存 到 + 文件类
    if (/写文件|创建文件|写代码|保存到|create file|write file|写\s*[一个份个]?\s*[^,]*文件|写\s*hello\s*world/i.test(task)) return 'write_file';
    if (/跑命令|运行|执行|exec|run/i.test(task)) return 'exec_command';
    if (/微信|发消息|wechat|message/i.test(task)) return 'send_wechat';
    if (/读|看|fetch|get|read/i.test(task)) return 'read_file';
    if (/搜|search|query|find|查/i.test(task)) return 'web_search';
    if (/截图|screenshot/i.test(task)) return 'screenshot';
    if (/下载|download/i.test(task)) return 'download_file';
    if (/压缩|打包|archive|zip|tar/i.test(task)) return 'archive_create';
    if (/解压|extract|unzip/i.test(task)) return 'archive_extract';
    
    // 默认:简单查询 → 不需 action
    return 'analyze_query';
  }
  
  _inferFilePath(task, params, hints) {
    // 1. 从 hints 取
    if (hints.path) return hints.path;
    if (params.path) return params.path;
    
    // 2. 从 task 文本提取 "/path/to/file" 或 "~/path"
    const pathMatch = task.match(/[~./][\w./\-]+\.\w{1,5}/);
    if (pathMatch) return pathMatch[0];
    
    // 3. 从 task 提取 "到 file.txt" 形式
    const toMatch = task.match(/到\s+([^\s,]+)/);
    if (toMatch) return toMatch[1];
    
    // 4. 默认走 /tmp + 自动文件名
    const filename = this._autoFilename(task);
    return `/tmp/${filename}`;
  }
  
  _inferContent(task) {
    // 简单处理:templates 优先
    if (/hello\s*world/i.test(task)) {
      return 'Hello, World!\n';
    }
    if (/json/i.test(task) && /配置|config/i.test(task)) {
      return '{\n  "name": "example",\n  "version": "1.0.0"\n}\n';
    }
    
    // 默认用任务描述作为内容
    return `# ${task}\n\nGenerated by Pangu Agent Cluster\n`;
  }
  
  _inferCmd(task) {
    if (/ls|list|查看|列出|文件/i.test(task)) return 'ls -la';
    if (/pwd|当前路径|当前目录/i.test(task)) return 'pwd';
    if (/date|时间|日期/i.test(task)) return 'date';
    if (/uname|系统|system/i.test(task)) return 'uname -a';
    if (/ps|进程/i.test(task)) return 'ps aux | head -20';
    
    // 默认:echo
    return `echo "${task}"`;
  }
  
  _autoFilename(task) {
    const t = task.toLowerCase().replace(/[^\w\s]/g, '').replace(/\s+/g, '_').slice(0, 30);
    return `pangu_${Date.now()}_${t}.txt`;
  }
  
  /**
   * 适配器列表(后续可注册多适配器)
   */
  registerAdapter(role, adapter) {
    if (!this.adapters) this.adapters = {};
    this.adapters[role] = adapter;
  }
}

const adapterInstance = new Adapter();

module.exports = {
  Adapter,
  adapt: (task, ctx) => adapterInstance.adapt(task, ctx),
  adaptTask: (task, ctx) => adapterInstance.adapt(task, ctx),
};
