'use strict';

// 2026-10-17 (tl-1792196710892): planner 的 depends_on 规则是**结构性的**, 不是
// 下游正则能补齐的。同一个「验收刀排到被验收对象前面」的 bug, 四次现场连撞四种措辞:
//   ①「仅依据上游 analyzer 的汇报结论」   ②「仅依据 analyzer 的汇报结论」
//   ③「analyzer 与 executor 的汇报结论」 ④「前两个子任务的汇报结论」(口语的"两")
// 每漏一种 = 验收刀与被验收的刀并发开审 → 审了个空 → 判 FAIL → 白触发补救循环,
// 现场一次 200 秒。下游推断是**兜底**, 真正的修法在源头: planner 必须自己写对。
//
// 结构性病根 (不是措辞问题, 是模板在教错):
//   planner 的「自查任务固定流程」模板里, 最后那刀「综合输出: 状态报告」
//   明摆着要吃前面四份检查结论, 模板却**没写 depends_on**。
//   planner 照着这个形状抄 → 学到"汇总/验收刀不用声明依赖"。
// 同一个模板还把 depends_on 说成"可选", 双重削弱。
//
// 这组断言钉住 prompt 契约: 模板要给对依赖、规则要说清必填、且**不许**矫枉过正
// (不能变成"什么都串起来" —— 那样并发归零, 比漏依赖更慢)。
const test = require('node:test');
const assert = require('node:assert');

const { ROLES } = require('../agents/sub-agent');
const P = ROLES.kan.system;

test('自查拆解不许再有写死的 5 刀清单 (扇出个数是盘古的判断)', () => {
  // 2026-10-18 (老板原话: «那问题就应该盘古判断几个agent并发, 不是人为控制agent并发»):
  // 原模板把 5 刀逐字写死在 prompt 里 (环境/架构/运行状态/工具清单 + "综合输出"),
  // 前四刀全是 checker。主人一句「做个全面体检」→ 4 个一模一样的兑并发 →
  // 2 条 300s 超时 (session 80004976), 老板截图问 «5个子agent, 全是兑, 那意义在哪?»。
  // 那个 5 就是这份清单, 所以清单必须删干净 —— 只留形状示范 (在【通用规则】里)。
  assert.ok(!/检查系统环境：主机名/.test(P), '不许再写死体检的第一刀');
  assert.ok(!/检查 Agent 架构：8 角色列表/.test(P), '不许再写死体检的第二刀');
  assert.ok(!/检查运行状态：进程监控/.test(P), '不许再写死体检的第三刀');
  assert.ok(!/检查工具清单：exec\/file\/network/.test(P), '不许再写死体检的第四刀');
  // 也不能换个名字继续写死 (模板块整体该消失)。
  assert.ok(!/综合输出：状态报告/.test(P),
    '"综合输出: 状态报告"那刀也删 —— 它跟父级 synthesis 重复, 且 5 刀总数就是它撑起来的');
  // 但"怎么判断"和"形状示范"必须留着 —— 只删清单不给方法, planner 会拆得更烂。
  assert.ok(/你要自己判断拆几刀|自己判断拆几刀/.test(P),
    '必须明说"拆几刀由你判断", 不然模型以为删了模板就没得抄了');
  assert.ok(/depends_on/.test(P), 'depends_on 的教学一个字都不能少 (这才是这块模板的真正价值)');
});

test('depends_on 规则不能再写成"可选"', () => {
  assert.ok(!/depends_on 可选/.test(P), '"可选"两个字是 planner 四次不写它的直接原因');
  assert.ok(/不是可选项|不是可选项,|不是可选项，/.test(P), '要说死: 这是必填的声明');
});

test('规则里必须有可照抄的「并行取证 → 验收刀串后面」示例', () => {
  assert.ok(P.includes('"depends_on":[0,1]'),
    '光讲道理不行, 必须给出正确形状让 planner 抄 (含 analyzer/executor 并行 + checker depends_on:[0,1])');
});

test('不许矫枉过正: 规则里要保留"别把互不相关的刀串起来"的告诫', () => {
  assert.ok(/别把"互不相关"的刀也串起来|互不相关.*串/.test(P),
    '过度串行会把并发清零 —— 2026-08-02 现场 5 个角色串行 = 8 分钟等不到 final');
});

test('规则要把「吃到上游结论」和「真正独立」这两类区分开', () => {
  assert.ok(/上游|前面几刀的结论|前N个/.test(P), '要给得出可判定的依据, 而不是"看着办"');
  assert.ok(/没提到就别写|就别写/.test(P), '也要说清独立任务不要乱声明, 否则并发归零');
});
