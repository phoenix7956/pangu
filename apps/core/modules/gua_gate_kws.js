/**
 * 卦资料查询 = 问"这卦是什么", 不是问"这卦对我意味着什么"。
 * 三条保护见 GUA_FACT_OVERRIDE_KWS 的注释。
 */
function isGuaFactLookup(text) {
  const t = String(text || '').toLowerCase();
  if (!t.trim()) return false;
  if (GUA_DECISION_KWS.some((k) => t.includes(k.toLowerCase()))) return false;   // 谋断优先
  if (GUA_CAST_REQUEST_KWS.some((k) => t.includes(k.toLowerCase()))) return false; // 明确要卦
  if (GUA_FACT_OVERRIDE_KWS.some((k) => t.includes(k.toLowerCase()))) return false;
  if (GUA_FACT_LOOKUP_KWS.some((k) => t.includes(k.toLowerCase()))) return true;
  if (GUA_FACT_LOOKUP_RE.test(t)) return true;
  return false;
}

/**
 * 主人**明确要卦**吗? (规则 19(a))
 * 单独成一个函数, 因为**分层编排**要判同一件事, 而它不在 pangu-single.js 里。
 */
function isGuaCastRequest(text) {
  const t = String(text || '').toLowerCase();
  if (!t.trim()) return false;
  return GUA_CAST_REQUEST_KWS.some((k) => t.includes(k.toLowerCase()));
}

/**
 * 谋断类显式信号吗? (该不该/要不要/趋势/风险/取舍…)
 * 分层编排用它区分「占问」与「普通执行」。
 */
function isDecisionQuestion(text) {
  const t = String(text || '').toLowerCase();
  if (!t.trim()) return false;
  return GUA_DECISION_KWS.some((k) => t.includes(k.toLowerCase()));
}

