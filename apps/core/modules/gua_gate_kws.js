/**
 * 这一句是**纯闲聊**吗? (起卦门用)
 *
 * 三层:
 *   ① 主人明说要卦 ⇒ **不是**纯闲聊 (规则 19(a): 明说要卦必调)。
 *      这一条顺带修掉一个老洞: 白名单原来排在最前, 于是「你好, 算一卦」被 '你好' 压掉
 *      ⇒ 主人明说要卦却没卦。
 *   ② 字面白名单 (includes) —— 旧口径, 逐位保留。
 *   ③ 概念层 —— 「你到底是谁」这类**插字**说法 (整句锚定)。
 */
function isPureChat(text) {
  const t = String(text || '').toLowerCase();
  if (!t.trim()) return false;
  if (isGuaCastRequest(t)) return false;
  if (PURE_CHAT_KWS.some((k) => t.includes(k.toLowerCase()))) return true;
  // ③ 身份/能力询问 —— 复用 answer_alignment 的真源 (单一真源, 不另抄)
  if (isSelfIntroAsk(t)) return true;
  return PURE_CHAT_CONCEPT_RES.some((re) => re.test(t));
}

