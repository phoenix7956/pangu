/**
 * 术数语境 —— 主人这句话**本身就在术数线上**。
 *
 * 为什么单独成一档 (2026-10-24 第 76 批, 实跑取证):
 *   上一版把「读取/读一下」塞进取数抑制表, 结果「读一下 /tmp/gua.md 里的卦辞」被误杀了 ——
 *   主人问的是卦, 却没拿到卦。**取数词表不该管术数题。**
 *   ⇒ 术数语境在抑制表**之前**就判掉: 这题归术数, 卦象照常出现。
 *
 * 词要**窄** (这一点是本档最容易踩的坑):
 *   裸 '占' 会命中「占用/统计占用」; 裸 '断' 会命中「判断/断点续传/中断」——
 *   那会把两个纯取数任务误判成占问, 方向正好反了 (该压的没压, 不该起的起了)。
 *   ⇒ 只用**术数专有的复合词**, 不用单字。
 *
 * 方向: **宁滥勿缺** (2026-10-21 纪律) —— 误杀谋断 (少一次卦象)
 *   比 多起一次卦 (有噪声) 贵得多。
 */
/**
 * 这句话本身是不是在术数线上?
 * @param {string} text 主人这一轮的原话
 * @returns {boolean}
 */
function isShushuContext(text) {
  const t = String(text || '').trim();
  if (!t) return false;
  // ⚠️ 正则**写在函数体内**, 不放模块级常量 ——
  //   原因: tests/helpers/gua_gate_load.js 把这个函数的**源码**注入到一个
  //   `new Function` 里求值 (线上 pangu-single.js 的 _shouldCastGua 靠它拿到词表)。
  //   模块级常量不会跟着源码走 ⇒ 注入后 ReferenceError, 那一档静默失效。
  //   (词表类的东西有专门注入通道; 正则这种「函数自己的零件」直接内联最稳。)
  // ⚠️ 词的**边界**也要管 (2026-10-24 补, 真流量+构造探针都命中过):
  //   · '体用' 会命中「具体用**户**」「具体用**途**」 —— 术数的「体用」指卦的
  //     主体/客体, 正常汉语里几乎不单独出现 ⇒ 收窄成「体用神 / 用神」这种
  //     术数专有搭配。
  //   · '断语' 会命中「打**断语句**」 ⇒ 改成「卦断 / 断卦 / 断语」三种
  //     实际说法, 且「断语」要求前后不是汉字 (断语句 就被挡住)。
  //   这两处都是**方向反了的误伤**: 术数语境档放行的代价是「普通取数任务被塞卦象」
  //   (噪声), 而这一档存在的意义是**别把真占问误杀**。⇒ 宁可少认几个词,
  //   也不能把「具体用户数」当成占问。
  return /(?:卦|爻|占卜|占一卦|占卦|卜卦|卜一卦|卦断|断卦|(?<![\u4e00-\u9fa5])断语(?![\u4e00-\u9fa5])|批命|算命|八字|生辰|合婚|风水|纳甲|六亲|体用神|用神|命理|卦象)/.test(t);
}

