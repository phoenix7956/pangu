const fs = require('fs');
const path = require('path');
const os = require('os');
// 2026-10-26 第 100 批: 账本目录走唯一真源 (modules/state_paths.js)
//   跟写方 (task_ledger.js) 共用同一个解析 ⇒ 读写不会分裂。
const statePaths = require('./state_paths');

const PANGU_HOME = process.env.PANGU_HOME || path.join(os.homedir(), '.pangu');
const LEDGER_DIR = () => statePaths.ledgerDir();

// 已知教训 kind → 守卫 token + 守卫所在源码文件 (相对 apps/core/)
const KIND_GUARDS = {
  EMPTY_CONTENT_ROUND: { token: 'EMPTY_CONTENT_ROUND', file: 'modules/j2_agent_loop.js' },
  WAIT_INSTRUCTION: { token: 'WAIT_INSTRUCTION', file: 'modules/j2_agent_loop.js' },
  PLAN_INCOMPLETE: { token: 'TASK_DONE_GATE', file: 'modules/j2_agent_loop.js' },
  LEDGER_MISS: { token: 'TASK_DONE_LEDGER_REJECT', file: 'modules/j2_agent_loop.js' },
  FAKE_OUTPUT: { token: 'FAKE_OUTPUT_GUARD', file: 'modules/j2_agent_loop.js' },
  FAKE_DELIVERY: { token: 'LEDGER_DELIVERY_REJECT', file: 'modules/j2_agent_loop.js' },
  HALLUCINATED_PATH: { token: 'paths_missing', file: 'modules/task_ledger.js' },
  PARTIAL_JUDGE: { token: 'LIP_SERVICE_TASK_DONE', file: 'modules/j2_agent_loop.js' },
  // 2026-10-23 第 71 批: 这个 kind 是第 59 批「进度判局并进六格内核」之后才出现的,
  // 之前没人登记 ⇒ 账本一扫到它就写 `assert.ok(false)` 把整条链拉红。
  // 守卫 token 选 judgeProgressShape: 它保证「判官判不出形状 ⇒ 走词法兜底,
  // 宁可不给结论也不拿空数据当结论」这条纪律还接着线。
  PROGRESS_JUDGE: { token: 'judgeProgressShape', file: 'modules/j2_agent_loop.js' },
};

function aggregateLessons() {
  const byKind = {};
  let files = 0;
  try {
    if (!fs.existsSync(LEDGER_DIR())) return { byKind, files };
    for (const f of fs.readdirSync(LEDGER_DIR())) {
      if (!f.endsWith('.json')) continue;
      files++;
      try {
        const data = JSON.parse(fs.readFileSync(path.join(LEDGER_DIR(), f), 'utf8'));
        for (const l of (data.lessons || [])) {
          const k = String(l.kind || '?');
          if (!byKind[k]) byKind[k] = { kind: k, count: 0, sessions: 0, last_note: '' };
          byKind[k].count += (l.count || 1);
          byKind[k].sessions++;
          byKind[k].last_note = sanitizeNote(String(l.note || '').slice(0, 120));
        }
      } catch (_) {}
    }
  } catch (_) {}
  return { byKind, files };
}

/**
 * 把账本 note 里的机器相关绝对路径洗掉。
 *
 * ── 为什么必须洗 ────────────────────────────────────────────────
 *   `tests/ledger-lessons.test.js` 是**签进仓里**的守卫文件 (每次反思自动重建),
 *   而 note 来自运行时账本 —— 里面常带本机路径 (例: 「声称写盘
 *   /Users/<某人>/.pangu/models-registry.json」)。
 *   ⇒ 开着服务跑一轮, 仓里就被写进了**本机绝对路径**,
 *     开源导出体检 (不许出现 /Users/<某人>/) 直接红 ⇒ **导出被卡死**。
 *   这跟「桌面剥离」是同一类问题: 机器状态不许漏进开源产物。
 *
 *   洗法: 本机家目录 → `~`; 别的机器的家目录前缀 (/Users/you/、/home/you/) → `~/`。
 *   只动**注释里的文字**, 不动断言逻辑 ⇒ 守卫强度不变。
 */
function sanitizeNote(note) {
  let s = String(note || '');
  const home = os.homedir();
  if (home) s = s.split(home).join('~');
  s = s.replace(/\/(?:Users|home)\/[A-Za-z0-9._-]+\//g, '~/');
  return s;
}

function renderTestFile(byKind) {
  // 2026-10-14 (老板 目标5 "其他问题"): 守卫集只增不减。
  // 旧码把「运行时账本里当前出现过的 kind」直接当成要断言的集合, 于是数据一空
  // (PANGU_HOME 指到别处 / 账本被清 / 换机器第一次跑) 就会把已经写死的 7 条真实
  // 回归守卫一起重建成 assert.ok(true) —— 守卫文件能自我摧毁, 而且静悄悄:
  // npm test 照样全绿, 直到某天旧死法真的复活才发现没人拦着。
  // KIND_GUARDS 是签进源码的持久知识, 任何时候都必须断言; 运行时账本只负责
  // 「发现新 kind」(未知 kind 仍然出红断言逼人来登记), 不负责「决定还剩哪些守卫」。
  const seenKinds = Object.keys(byKind).sort();
  const kinds = Array.from(new Set([...Object.keys(KIND_GUARDS).sort(), ...seenKinds])).sort();
  const lines = [
    '// AUTO-GENERATED by apps/core/modules/ledger_reflect.js — 请勿手改 (每日反思自动重建)',
    '// 账本教训 → 回归守卫: 每个真实死因 kind 必须在源码里有对应守卫 token, 缺失即红。',
  ];
  if (!seenKinds.length) {
    lines.push('// 本次账本扫描 0 条 —— 下面这些守卫来自 KIND_GUARDS 注册表, 一条都没少 (守卫集只增不减)');
  }
  lines.push(
    "'use strict';",
    "const assert = require('assert');",
    "const fs = require('fs');",
    "const path = require('path');",
    "const CORE = path.join(__dirname, '..');",
    "function src(rel) { return fs.readFileSync(path.join(CORE, rel), 'utf8'); }",
    '',
  );
  for (const k of kinds) {
    const g = KIND_GUARDS[k];
    const info = byKind[k];
    // 没在本次账本里复现的 kind 也要留注释位 —— 让人一眼看出「这次没死法, 不是没守卫」。
    const stat = info
      ? `实发 ${info.count} 次 / ${info.sessions} 会话. 最近: ${info.last_note.replace(/\n/g, ' ')}`
      : '本次账本未复现 (守卫仍在位, 历史死法没被忘)';
    lines.push(`// ${k} — ${stat}`);
    if (g) {
      lines.push(`assert.ok(src(${JSON.stringify(g.file)}).includes(${JSON.stringify(g.token)}), '教训 ${k} 的守卫 ${g.token} 在 ${g.file} 中缺失 — 守卫被删, 旧死法复活');`);
    } else {
      lines.push(`assert.ok(false, '新教训 kind "${k}" 无守卫 (实发 ${info.count} 次) — 先在 ledger_reflect.js KIND_GUARDS 登记守卫 token 并确认源码有对应守门');`);
    }
    lines.push('');
  }
  lines.push("console.log('ledger-lessons guard test OK (" + kinds.length + " kinds)');");
  lines.push('');
  return lines.join('\n');
}

// 主入口 — scheduler pangu.self_reflect 调用
function reflectLessons() {
  const { byKind, files } = aggregateLessons();
  const testFile = path.join(__dirname, '..', 'tests', 'ledger-lessons.test.js');
  const content = renderTestFile(byKind);
  try {
    fs.mkdirSync(path.dirname(testFile), { recursive: true });
    fs.writeFileSync(testFile, content);
  } catch (e) {
    return { ok: false, error: e.message };
  }
  const kinds = Object.keys(byKind).sort();
  const unknown = kinds.filter(k => !KIND_GUARDS[k]);
  return {
    ok: unknown.length === 0,
    ledgers_scanned: files,
    kinds,
    unknown_kinds: unknown,
    // 渲染进守卫文件的 kind (注册表并集) —— 恒 >= KIND_GUARDS, 不受账本空/非空影响。
    guard_kinds: Array.from(new Set([...Object.keys(KIND_GUARDS), ...kinds])).sort(),
    file: testFile,
  };
}

module.exports = { reflectLessons, aggregateLessons, renderTestFile, sanitizeNote, KIND_GUARDS };
