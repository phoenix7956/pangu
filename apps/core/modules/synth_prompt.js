// 长版(取自 L373): 比三份短版多一句「不要因为某一句自述就断言整轮没干活」。
const RECONCILE_RULE =
  '【对账铁律】子 agent 的自述是各自那个时点的快照，先跑的那个说"未创建/未修改任何文件"'
