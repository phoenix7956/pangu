const LENGTH_RULE_BREADTH =
  '【长度】主人这一轮明确要覆盖面 (分别/逐条/详细/全面/对比之类), '
  + '**本轮不适用 300 字上限** —— 但仍然禁止过程碎碎念、认错长段、客套收尾。'
