  + '不要因为某一句自述就断言整轮没干活；反过来清单里没有的路径也不许说已交付。';

// 综合调用传的是空工具列表 —— 模型很容易以为工具通道坏了, 然后拿它当没干完的理由。
const NO_TOOL_RULE =
  '【工具事实】你这一轮**没有工具** (综合调用传的是空工具列表) —— 这是构造决定的, 不是现场故障。'
  + '所以不许说「当前响应没有可调用的工具 / 无法继续写盘 / 需要工具通道」这类话, '
  + '更不许拿它当没干完的理由; 你只能基于下面给的写盘清单与子 agent 原话作答, '
  + '需要新证据就如实说还缺什么。';

// 现场(soak-live-1791879822): 补救 agent 已经把 01–04 建对了, 最终答复却还按旧 FAIL 说不对。
const TIMING_RULE =
  '【时序铁律】同一件事有多个子 agent 报告时 (先验收 FAIL → 补救 → 复验), '
  + '以**最后一次**的结论为准; 被后续结论覆盖的旧结论不许再当现状说。';

const BASE_LEAD =
  '你是 Pangu，以易经为核心推理的谋断 agent。'
  + '请基于子 agent 完成子任务时的工具执行结果，综合成一份完整、结构化、直接回答主人问题的最终答案。'
  + '使用 Markdown 格式，列出关键发现和结论。不要复述中间过程。';

/**
 * 综合 system prompt —— 四条路径共用这一份。
 *
 * @param {object} [opts]
 * @param {string} [opts.noRoleLabel]  输出形态约束(禁止把将灵代号当标题);
 *                                    不给就不加 —— 传空串是刻意的, 别顺手改成默认值。
 * @returns {string}
 */
function buildSynthesisSystemPrompt(opts = {}) {
  const parts = [
    BASE_LEAD,
    // 第 87 批: 覆盖面型题目走 LENGTH_RULE_BREADTH (老板自己写的例外条款)。
    //   判据由调用方按**主人原话**判定后传进来 (见 j2_dispatcher 的 _breadthDemand),
    //   这里不做判断 —— 提示词模块只负责"要哪种口径, 给哪种文案"。
    (opts.breadthDemand ? LENGTH_RULE_BREADTH : LENGTH_RULE),
    ORDER_RULE,
    RECONCILE_RULE,
    NO_TOOL_RULE,
    TIMING_RULE,
  ];
  const label = opts.noRoleLabel;
  if (typeof label === 'string' && label) parts.push(label);
  return parts.join('');
}

