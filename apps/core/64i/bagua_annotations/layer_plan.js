/**
 * 64i/bagua_annotations/layer_plan.js
 * 分层编排 —— 「什么时候用阴阳五行八卦, 什么时候用 64 卦+6 爻, 什么时候串起来」
 *
 * 起因 (老板 2026-10-23 原话, 一字不改):
 *   「所以, 现在的盘古到底是什么情况? 要怎么处理?
 *      什么时候用阴阳五行八卦, 什么时候 64卦+6爻? 什么时候串起来用?」
 *
 * 这个问题此前**没有落点**:
 *   · 全局规则 #19 只讲 64 卦(何时起卦/何时走 hexagram_lookup),
 *     **一个字没提 bazi_calc、没提六格判局、没提「串起来」**。
 *   · 出处台账把每一层都登得很好, 但那是给**机器**看的; 模型看不见台账。
 *   · 工具描述里 `gua_cast` 只有 9 个字符、`bazi_calc` 16 个字符 ——
 *     模型拿到的说明书等于没有(且 li 角色 schema 已 8987/9000, 塞不进去)。
 * ⇒ 本模块是那套「什么时候用哪层」的**唯一真源**: 规则、探测器、注入给模型的那一行,
 *   三处都从这里取, 不各写一份。
 *
 * 分层规矩 (跟 tiyong / wuxing_strength 那几层一样):
 *   本文件只放**数据**(五层定义 LAYERS / 路由表 ROUTES / 身份标签 LAYER_PLAN_TAG);
 *   **渲染**(拼给模型看的那一行)与**探测**(判这题走哪层)在 modules/layer_plan.js。
 *   为什么: 生产层渲染点住在 modules/ 是盘古既有的先例(见 64i/tiyong_axioms.js 的
 *   TIYONG_GRADE_TAG ↔ modules/gua_block.js:buildTiYongLine), 出处台账 P12 守卫
 *   也按这个形状检查(渲染点函数体里必须**引用**标签常量, 不能手写字面量)。
 *   ⇒ 渲染器只有一份(在 modules/), 标签只有一份(在这里), 两边不许各写一遍。
 *
 * ═══════════════════════════════════════════════════════════════
 * 五层是什么
 * ═══════════════════════════════════════════════════════════════
 *
 *   ① 阴阳五行八卦层 —— 以**五行生克 + 八卦属性**推。
 *      问的是**长期状态**: 这个人的旺衰/用神/十神、这个方位的五行、两个人的合婚。
 *      入口: bazi_calc。依据: wuxing_axioms / wuxing_strength / wuxing_yinyang。
 *
 *   ② 64 卦+6 爻层 —— 以**卦爻辞 + 动爻 + 装卦**推。
 *      问的是**此刻此地的一件事**: 该不该做、何时动、往哪走。
 *      入口: gua_cast。依据: hexagrams / yao_models / najia / jingfang_bagong。
 *
 *   ③ 串起来层 —— **纳甲就是那座桥**。
 *      纳甲把卦/爻接到干支五行上(内三爻取下卦、外三爻取上卦),
 *      干支五行才有得令失令、生克强弱, 六亲才立得起来。
 *      ⇒ 「既问方向又问落地」(某人今年运势如何、又该不该动) = ② + ①, 用 ③ 连。
 *      依据: najia.js(装法规则与爻级地支)、task_judge.js(六亲口径)。
 *
 *   ④ 生彼泻克耗六格层 —— 给**一件事**出结构判断与停点。
 *      这是老板 10-21 亲手给的表, 原话「就拿八字排盘…但是这用在项目上,
 *      加强了停顿, 走一步判断一步, 而且挂永远没有100%」。
 *      入口: wuxing_judge。依据: task_judge.js。
 *
 *   ⑤ 64i 资料层 —— 问 64 卦**本身**的资料(第N卦是哪一卦/卦辞爻辞/纳甲八宫)。
 *      这是**查表**不是占问。入口: hexagram_lookup。依据: hexagrams.js。
 *
 * ═══════════════════════════════════════════════════════════════
 * 两种「串起来」别混
 * ═══════════════════════════════════════════════════════════════
 *
 *   · **卦 ↔ 干支串**(第 ③ 层): 易经内部的桥, 纳甲。
 *     卦给方向(吉凶/时机), 干支五行给落地(旺衰/六亲/用神)。
 *   · **卦 ↔ 六格串**(第 ⑥ 型): 项目上的事, 卦给方向, 六格给结构与停点。
 *     老板原话「这用在项目上, 加强了停顿, 走一步判断一步」——
 *     六格负责「走一步判断一步」, 卦负责「这一步往哪走」, **不是二选一**。
 *
 * ═══════════════════════════════════════════════════════════════
 * 出处诚实: 每一层的**依据**有源, 「什么时候用哪层」这个映射本身是盘古的编排设计
 * ═══════════════════════════════════════════════════════════════
 *
 *   ① ② ③ ⑤ 的判据都有典籍/课件/老板原话可核(见各自依据层, 本模块不重抄,
 *     改一处就在两处漂 —— 第 55 批搬 tiyong 就是为了这个)。
 *   ④ 的术数名有源(生我者/我生者/克我者/我克者/同我者), 任务语义对应是老板口述 ⇒ interpretive。
 *   而 **「什么时候用哪层」这个映射本身**, 是盘古的编排设计 + 老板几次口头裁定
 *     (2026-08「卦先于推理」/ 2026-10-09「事实在前卦象在后」/ 2026-10-21「用在项目上」)
 *     —— 不是任何典籍的断语 ⇒ 本模块标 interpretive, 并在生产文本上标身份。
 */

